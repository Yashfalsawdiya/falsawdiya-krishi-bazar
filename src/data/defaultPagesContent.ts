// Default export is clean Hindi
export const DEFAULT_LEGAL_PAGES_CONTENT = DEFAULT_LEGAL_PAGES_CONTENT_HI;

/**
 * Localized legal pages provider
 * Returns pure Hindi in 'hi' mode and pure English in 'en' mode.
 */
export const getLocalizedLegalPages = (
  customContent?: Partial<LegalPagesContent>,
  lang: 'hi' | 'en' = 'hi'
): Required<LegalPagesContent> => {
  const baseDefaults = lang === 'en' ? DEFAULT_LEGAL_PAGES_CONTENT_EN : DEFAULT_LEGAL_PAGES_CONTENT_HI;

  if (!customContent) {
    return baseDefaults;
  }

  // Merge any custom content provided by admin, ensuring default fallback fields are properly populated
  return {
    aboutUs: { ...baseDefaults.aboutUs, ...(customContent.aboutUs || {}) },
    privacyPolicy: { ...baseDefaults.privacyPolicy, ...(customContent.privacyPolicy || {}) },
    termsConditions: { ...baseDefaults.termsConditions, ...(customContent.termsConditions || {}) },
    refundPolicy: { ...baseDefaults.refundPolicy, ...(customContent.refundPolicy || {}) },
    aiDisclaimer: { ...baseDefaults.aiDisclaimer, ...(customContent.aiDisclaimer || {}) },
    chemicalSafety: { ...baseDefaults.chemicalSafety, ...(customContent.chemicalSafety || {}) },
    contactUs: { ...baseDefaults.contactUs, ...(customContent.contactUs || {}) },
    faqHelp: { ...baseDefaults.faqHelp, ...(customContent.faqHelp || {}) },
    shippingPolicy: { ...baseDefaults.shippingPolicy, ...(customContent.shippingPolicy || {}) },
    grievanceRedressal: { ...baseDefaults.grievanceRedressal, ...(customContent.grievanceRedressal || {}) },
    licensingDisclaimer: { ...baseDefaults.licensingDisclaimer, ...(customContent.licensingDisclaimer || {}) }
  };
};

/**
 * Helper to fetch a single page data cleanly
 */
export const getLegalPageData = <K extends keyof LegalPagesContent>(
  pageKey: K,
  customContent: Partial<LegalPagesContent> | undefined,
  lang: 'hi' | 'en' = 'hi'
): Required<LegalPagesContent>[K] => {
  const allPages = getLocalizedLegalPages(customContent, lang);
  return allPages[pageKey];
};
