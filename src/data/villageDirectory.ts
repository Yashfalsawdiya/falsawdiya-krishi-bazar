export const PRIMARY_TEHSILS = [
  'शामगढ़',
  'गरोठ',
  'सुवासरा',
  'सीतामऊ',
  'भानपुरा',
  'मंदसौर',
  'अन्य',
];

/**
 * Normalizes text for robust bilingual comparison (Hindi & English)
 */
export const normalizeLocationText = (str: string = ''): string => {
  return str
    .toLowerCase()
    .trim()
    .replace(/[.,\-_/()]/g, ' ')
    .replace(/\s+/g, ' ');
};

/**
 * Returns the active village directory.
 * If configuredVillages is provided and non-empty, it directly respects all user additions,
 * updates, and deletions (preventing resurrection of deleted villages or tehsils).
 */
export const getCombinedVillageDirectory = (
  configuredVillages?: VillageDeliveryEntry[]
): VillageDeliveryEntry[] => {
  if (Array.isArray(configuredVillages) && configuredVillages.length > 0) {
    return configuredVillages;
  }
  return DEFAULT_VILLAGE_DIRECTORY;
};

/**
 * Extracts unique Tehsil list with counts and active status
 */
export const getAllTehsilsFromDirectory = (
  allVillages?: VillageDeliveryEntry[]
): { tehsil: string; total: number; active: number }[] => {
  const list = allVillages || DEFAULT_VILLAGE_DIRECTORY;
  const tehsilMap: Record<string, { total: number; active: number }> = {};

  // First seed known primary tehsils
  for (const t of PRIMARY_TEHSILS) {
    if (t !== 'अन्य') {
      tehsilMap[t] = { total: 0, active: 0 };
    }
  }

  // Count from villages
  for (const v of list) {
    const t = v.tehsil || 'अन्य';
    if (!tehsilMap[t]) {
      tehsilMap[t] = { total: 0, active: 0 };
    }
    tehsilMap[t].total += 1;
    if (v.isActive) {
      tehsilMap[t].active += 1;
    }
  }

  return Object.entries(tehsilMap).map(([tehsil, stats]) => ({
    tehsil,
    total: stats.total,
    active: stats.active,
  }));
};

/**
 * Searches tehsils matching user query
 */
export const searchTehsils = (
  query: string,
  allVillages?: VillageDeliveryEntry[]
): string[] => {
  const clean = normalizeLocationText(query);
  const tehsils = getAllTehsilsFromDirectory(allVillages).map(item => item.tehsil);
  if (!clean) return tehsils;
  return tehsils.filter(t => normalizeLocationText(t).includes(clean));
};

/**
 * Filters villages matching a specific Tehsil
 */
export const getVillagesByTehsil = (
  tehsil: string,
  allVillages?: VillageDeliveryEntry[]
): VillageDeliveryEntry[] => {
  const list = allVillages || DEFAULT_VILLAGE_DIRECTORY;
  const cleanTehsil = normalizeLocationText(tehsil);

  if (!cleanTehsil || cleanTehsil === 'अन्य') {
    return list;
  }

  return list.filter((v) => {
    const vTehsil = normalizeLocationText(v.tehsil);
    return vTehsil.includes(cleanTehsil) || cleanTehsil.includes(vTehsil);
  });
};

/**
 * Searches a village entry matching either Hindi name, English name, or phonetics
 */
export const findVillageMatch = (
  queryText: string,
  tehsilHint?: string,
  allVillages?: VillageDeliveryEntry[]
): VillageDeliveryEntry | null => {
  const cleanQuery = normalizeLocationText(queryText);
  if (!cleanQuery || cleanQuery.length < 2) return null;

  const list = allVillages || DEFAULT_VILLAGE_DIRECTORY;

  // 1. Exact match with both name and tehsil
  if (tehsilHint) {
    const cleanTehsil = normalizeLocationText(tehsilHint);
    const exactWithTehsil = list.find((v) => {
      const vNameHi = normalizeLocationText(v.nameHi);
      const vNameEn = normalizeLocationText(v.nameEn);
      const vTehsil = normalizeLocationText(v.tehsil);
      const isTehsilMatch = vTehsil.includes(cleanTehsil) || cleanTehsil.includes(vTehsil);
      const isNameMatch = vNameHi === cleanQuery || vNameEn === cleanQuery || 
        vNameHi.includes(cleanQuery) || vNameEn.includes(cleanQuery);
      return isTehsilMatch && isNameMatch;
    });
    if (exactWithTehsil) return exactWithTehsil;
  }

  // 2. Direct name match (Hindi or English)
  const directMatch = list.find((v) => {
    const vNameHi = normalizeLocationText(v.nameHi);
    const vNameEn = normalizeLocationText(v.nameEn);
    return (
      vNameHi === cleanQuery ||
      vNameEn === cleanQuery ||
      cleanQuery.includes(vNameHi) ||
      cleanQuery.includes(vNameEn)
    );
  });

  if (directMatch) return directMatch;

  // 3. Partial substring match
  const partialMatch = list.find((v) => {
    const vNameHi = normalizeLocationText(v.nameHi);
    const vNameEn = normalizeLocationText(v.nameEn);
    return vNameHi.includes(cleanQuery) || vNameEn.includes(cleanQuery);
  });

  return partialMatch || null;
};
